"""🖼️ Khung danh hiệu, step 2: the frames the game wears (public/js/v4/honour-frames.js) as small WebP files.

usage: python -I scripts/build_honour_frames.py <cut dir of scripts/cut_honour_frames.py>
Writes public/icons/frames/<n>_av.webp (the window's diameter AV_D px), <n>_chat.webp (CHAT_SCALE of the board) and
public/js/v4/honour-frames-data.js: FRAMES[n] = {av: [w, h, cx, cy, r, square], chat: [w, h, x0, y0, x1, y1]}.
"""
import json
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'public', 'icons', 'frames')
DATA = os.path.join(ROOT, 'public', 'js', 'v4', 'honour-frames-data.js')
# the boards worn (honour-frames.js TIERS, CAREER, CAREER_ANY, WORN and the auction's 60)
IDS = ('03', '14', '16', '18', '20', '21') + tuple(f'{i:02d}' for i in range(25, 69)) + ('72',)
# 🆓 the everyday frames anyone may wear (honour-frames.js FREE, owner 18/10 "cho người ta chọn khung mặc định nữa")
IDS += ('01', '02', '05', '19', '22', '23', '24')
SQUARE = {'50', '52', '53', '54', '60', '24'}   # a squarish window: the picture keeps rounded corners, not a circle
AV_D = 120
CHAT_SCALE = 0.4


STRIP = 6   # px of the picture stretched across and down a chat bubble: a plain piece of the rim (slices())


def _strip(lo, diff):
    """The first line (from `lo`) of the STRIP lines to stretch: where the picture changes least from line to line
    (`diff`: the change from each line to the next), so repeating them looks like the rim drawn
    longer; the middle one among equals."""
    if len(diff) < STRIP:
        return None
    win = np.convolve(diff, np.ones(STRIP), 'valid')
    mid = (len(win) - 1) / 2
    win = win + (win.max() + 1) * 1e-3 * np.abs(np.arange(len(win)) - mid) / max(mid, 1)
    return lo + int(win.argmin())


def _extra(n):
    """A cost per line for the opaque pixels beside the text box over the rim's own (the lightest fifth + 2): a flower,
    a ribbon end there would be drawn into a long bar even where it changes little from line to line."""
    return np.maximum(n.astype(float) - np.percentile(n, 20) - 2, 0) * 600


def slices(img, box):
    """The 9-slice cuts [top, right, bottom, left] (px of the picture) of a chat bubble (honour-frames.js bubble()).
    Only a STRIP-wide piece is stretched, across the bubble and down it, where the picture looks the same from line to
    line: every decoration (the cat's head, the rabbit, a straw, leaves, a roof, the speech tail)
    stays in a corner at its own shape, never stretched or cut in two (owner 18/10: "mèo với thỏ bị lỗi khi nhắn rồi,
    bị cắt", "nhiều cái … méo méo")."""
    w, h = img.size
    x0, y0, x1, y1 = box
    a = np.asarray(img.convert('RGBA')).astype(float)
    p = a[:, :, :3] * a[:, :, 3:] / 255   # premultiplied: a transparent pixel is black whatever its colour
    p = np.concatenate([p, a[:, :, 3:]], 2)
    al = a[:, :, 3] > 40
    ry = min(.32 * (y1 - y0), 40)
    rx = min(ry, .2 * (x1 - x0))
    s = [y0 + ry, w - x1 + rx, h - y1 + ry, x0 + rx]
    pad = 6   # off the window's rounded corners
    ys = range(y0 + pad, y1 - pad)
    if len(ys) > STRIP:
        d = np.abs(np.diff(p[ys.start:ys.stop + 1], axis=0)).sum((1, 2))   # the whole line: the plain fill adds ~0
        d = d + _extra(al[ys.start:ys.stop, :x0].sum(1)) + _extra(al[ys.start:ys.stop, x1:].sum(1))
        m = _strip(ys.start, d)
        s[0], s[2] = m, h - (m + STRIP)
    xs = range(x0 + pad, x1 - pad)
    if len(xs) > STRIP:
        d = np.abs(np.diff(p[:, xs.start:xs.stop + 1], axis=1)).sum((0, 2))
        d = d + _extra(al[:y0, xs.start:xs.stop].sum(0)) + _extra(al[y1:, xs.start:xs.stop].sum(0))
        m = _strip(xs.start, d)
        s[3], s[1] = m, w - (m + STRIP)
    return [round(v) for v in s]


def main():
    cut = sys.argv[1]
    meta = json.load(open(os.path.join(cut, 'meta.json'), encoding='utf-8'))
    os.makedirs(OUT, exist_ok=True)
    frames = {}
    for n in IDS:
        m = meta[n]
        av = Image.open(os.path.join(cut, f'{n}_av.png'))
        k = AV_D / (2 * m['av']['r'])
        av = av.resize((round(av.width * k), round(av.height * k)), Image.LANCZOS)
        av.save(os.path.join(OUT, f'{n}_av.webp'), 'WEBP', quality=86, method=6)
        a = m['av']
        frames[n] = dict(av=[av.width, av.height, round(a['cx'] * k, 1), round(a['cy'] * k, 1), round(a['r'] * k, 1), int(n in SQUARE)])
        ch = Image.open(os.path.join(cut, f'{n}_chat.png'))
        ch = ch.resize((round(ch.width * CHAT_SCALE), round(ch.height * CHAT_SCALE)), Image.LANCZOS)
        ch.save(os.path.join(OUT, f'{n}_chat.webp'), 'WEBP', quality=86, method=6)
        box = [round(v * CHAT_SCALE) for v in m['chat']['box']]
        frames[n]['chat'] = [ch.width, ch.height] + box + slices(ch, box)   # + the 9-slice cuts (slices())
    body = ',\n'.join(f"  '{n}':{json.dumps(v, separators=(',', ':'))}" for n, v in frames.items())
    js = ('/** 🖼️ Generated by scripts/build_honour_frames.py: the sizes of public/icons/frames/*.webp (px of each file).\n'
          ' * av: [w, h, window centre x, y, radius, squarish]; chat: [w, h, text box x0, y0, x1, y1]. */\n'
          f'export const FRAMES={{\n{body}\n}};\n')
    open(DATA, 'w', encoding='utf-8', newline='\n').write(js)
    total = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
    print(len(frames), 'frames,', round(total / 1024), 'KB')


if __name__ == '__main__':
    main()
