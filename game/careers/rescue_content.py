# ---------------------------------------------------------------- the calls
# cat: 'real' (send), 'doubt' (truth decided by a hidden trait: check before you decide), 'junk' (no unit).
# addr: 'ok' (the address answers), 'vague' (+ a landmark), 'lost' (a location link, or a landmark and a passer-by).
# ans: the five script answers; fake: the answers when a doubtful call is not real; clues: listen/probe/recall.
# prio/teams/ok_teams: the right send; ok_prio: also fine. key: instructions that must be read out;
# cards: the instruction cards shown (good and tempting). stay: keep the line open until the team arrives.
# panic/mood: ranges of the hidden traits; soothe: the calming that works best on this caller.
# to/ok_to: where a call with nobody to send goes. hang: the line drops after the first answer (call back).
def _c(cid, cat, emoji, label, npc, opening, ans, addr='ok', prio='p4', teams=(), ok_teams=(), ok_prio=(), key=(), cards=(), stay=False,
       panic=(0, 0), mood=(0, 1), soothe='name', to=None, ok_to=(), real=1.0, fake=None, clues=None, hang=False, lost=None, push=None):
    return dict(id=cid, cat=cat, emoji=emoji, label=label, npc=npc, opening=opening, ans=ans, addr=addr, prio=prio, teams=tuple(teams),
                ok_teams=tuple(ok_teams), ok_prio=tuple(ok_prio), key=tuple(key), cards=tuple(cards), stay=stay, panic=panic, mood=mood,
                soothe=soothe, to=to, ok_to=tuple(ok_to), real=real, fake=fake or {}, clues=clues or {}, hang=hang, lost=lost or {},
                push=push or [])


