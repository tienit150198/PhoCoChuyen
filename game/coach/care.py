"""🧭 Coach steps of the care and service careers (see game/coach/__init__.py): the child, the patient, the class, the
group, the reader, the caller, the swimmer, the resident, the island and the crossing, each from taking the case to
handing it over.

These careers have no stock to order (the library's supply room aside): their loop is their own. A choice the player
must make (a greeting, a priority, an answer) rings the whole group of choices, never one of them. A job's finishing
button is matched by its command only while it can go (`:not(.is-why)`: a dimmed one says why on a tap and sends
nothing), so the coach waits ("not on screen yet") instead of ringing a button that is not ready."""
from . import S, V, stock  # noqa: F401


def nxt() -> dict:
    """Between two jobs: the done screen's way on (only when it is there): the next waiting job, or a new one when
    none is waiting yet (the shift's jobs come in over the day)."""
    return S('➡️', 'Bấm Công việc tiếp theo, hoặc nhận việc mới.', ['Công việc tiếp theo'],
             ['[data-action="nextJob"]', '#sheet[open] [data-command="more_work"]'], o=True)


def fin(e: str, t: str, cmd: str, *, loose: bool = False, **kw) -> dict:
    """A job's finishing button (the bottom bar's main button). Rung only once the game's own steps are done (the
    button is the command itself then); `loose`: also its confirm ("Còn n bước chưa xong… Vẫn làm luôn?"), for a
    job whose checklist keeps a row that only some cases fill (a doctor call, a gale warning)."""
    sel = [f'[data-command="{cmd}"]:not(.is-why)'] + ([f'[data-op="{cmd}"]:not(.is-why)'] if loose else [])
    return S(e, t, s=sel, **kw)


def more(e: str, t: str, sel: str, n: int, **kw) -> list[dict]:
    """The rest of a list read one by one (the night's notes, the duty book, the radio round): one quiet step per
    item left, each gone once the list is done."""
    return [S(e, t, s=[sel], o=True, **kw) for _ in range(n)]


def intro(cmd: str, label: str = 'Vào ca thôi!') -> dict:
    """The street kit's career intro card: its start button shows once."""
    return S('👋', f'Bấm {label} để bắt đầu.', [label, 'Vào việc thôi!'], [f'[data-command="{cmd}"]'], o=True)


def again(step: dict) -> dict:
    """The same step once more, quietly: in the first jobs a mentor (chị Hoa, anh Hải…) may stop a wrong choice
    before it counts; the job is then still there and its control is rung again (gone if the choice went through)."""
    return dict(step, o=1)


def ask(e: str, t: str, label: str, **kw) -> dict:
    """The street kit's ask card: the one button that brings the next person (or case) in. Matched by its words
    (each kind of job has its own: "Nhận đồ từ người nhặt", "Bắt đầu tuần tra"), not by .sk-ask, so a step never
    rings the next job's card."""
    return S(e, t, [label], **kw)


