"""🧭 Coach steps of the food places and the stays (see game/coach/__init__.py): the career's intro card, the morning
set-up where there is one, one customer from the ask to the money, then the stock round.

Many of these screens carry the game's own next-step button at the bottom (v4/guide.js stepBar: `.gd-cta`, the same
command and the right choice for this customer): a step whose control is one of several look-alike buttons (which
fire, which water level, which bowl) rings that button first, then the control itself."""
from . import S, V, stock  # noqa: F401

# The stock room of the street-kit places is a dock entry (app.js dockItems: "Kho" on the phone bar, its full name
# elsewhere): from the work sheet the player closes the sheet first.
CLOSE_SHEET = V('Đóng bảng này, Kho ở thanh dưới.', ['Đóng'], ['#sheet[open] .sheet-head [data-action="close"]'])
DOCK_W = 'Nút Kho ở thanh dưới, khi đóng bảng việc.'


def dock_stock(name: str, t: str, *, g=('prep', 0)) -> list[dict]:
    """The stock round of a place whose stock room is the dock's 'inventory' entry."""
    return stock(list(dict.fromkeys(['Kho', name])), ['[data-action="inventory"]'], g=g, t=t, v=CLOSE_SHEET, w=DOCK_W)


def intro(cmd: str) -> dict:
    """The career's intro card (street_kit introCard): its "Vào việc thôi!" button, shown once."""
    return S('👋', 'Bấm Vào việc thôi! để vào việc.', ['Vào việc thôi!'], [f'[data-command="{cmd}"]'], o=True)


def cta(cmd: str, *more: str) -> list[str]:
    """The game's next-step button for `cmd` first (it carries the right choice), then `more`, then the control."""
    return [f'.gd-cta[data-command="{cmd}"]', *more, f'[data-command="{cmd}"]']


def final(cmd: str) -> list[str]:
    """A finishing button only once the bottom bar offers it as the main button (all steps done): never the quiet
    "hoặc …" link that finishes early with a "Còn N bước" question, nor the dimmed one that only says why (a tap
    on it sends nothing, and the coach would count it as done)."""
    return [f'.gd-cta[data-command="{cmd}"]:not(.is-why)', f'.gd-cta[data-op="{cmd}"]:not(.is-why)']


def opened(cmd: str, t: str, *, g=None) -> dict:
    """The morning's opening button (MỞ QUÁN…): it waits for the set-up to be done."""
    return S('☀️', t, [], final(cmd), g=g,
             w='Xong việc buổi sáng thì nút này hiện ở thanh dưới.')


def till(cmd: str, g) -> list[dict]:
    """The cash tray (careers/till.js): notes into the change tray, then the hand-over button."""
    return [S('🪙', 'Chạm tờ tiền để đặt đủ tiền thối vào khay.', [],
              ['.gd-cta[data-action="car:tillAdd"]', '[data-till] [data-action="car:tillAdd"]', '[data-till]'], g=g,
              w='Khay tiền hiện khi khách trả tiền.'),
            S('💵', 'Bấm ĐƯA TIỀN THỐI để trả tiền thối.', [], final(cmd), g=g,
              w='Đặt đủ tiền thối thì nút hiện ở thanh dưới.')]


# A control only while it can be pressed (a dimmed one says why on a tap and sends nothing).
READY = '{}:not(.is-why):not([disabled])'


def coat(layer: str) -> str:
    """One of the nail polish coat buttons (base, colour, top: the same command, the layer in the payload)."""
    return f'[data-command="nl_coat"][data-payload*=\'"layer":"{layer}"\']'


def ask(label: str | list[str], t: str, cls: str = '.sk-ask', g=0) -> dict:
    return S('👂', t, label, [cls, '[data-command="ask"]'], g=g, w='Nút hiện khi có khách tới.')


