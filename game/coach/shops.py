# The change tray (careers/till.js): the note the game's own next step names, while it names one.
DENOMS = (500, 200, 100, 50, 20, 10, 5, 2, 1)
NOTE = [f'#sheet:has(.gd-next [data-action="car:tillAdd"][data-v="{v}"]) [data-till] [data-action="car:tillAdd"][data-v="{v}"]' for v in DENOMS]
NOTE_ANY = '#sheet:has(.gd-next [data-action="car:tillAdd"]) [data-till] .till-denoms'
UNDO = '#sheet:has(.gd-next [data-action="car:tillUndo"]) [data-till] [data-action="car:tillUndo"]'


def change(g, undo_g=None) -> list[dict]:
    """Change into the tray, one note per step while the game still asks for one (each step drops out when not)."""
    note = S('💵', 'Chạm tờ tiền để đặt đủ tiền thối vào khay.', s=[*NOTE, NOTE_ANY], g=g, o=True)
    back = S('↩️', 'Đặt dư rồi: bấm Bớt tờ cuối.', s=[UNDO], g=undo_g if undo_g is not None else g, o=True)
    return [note, note, note, back, note, note]


def till(cmd: str, g, labels=('ĐƯA TIỀN THỐI',)) -> list[dict]:
    """The change tray, then the hand-over."""
    return [*change(g),
            S('🪙', f'Bấm {labels[0]} để thối tiền.', list(labels), [f'[data-command="{cmd}"]', f'[data-op="{cmd}"]'], g=g,
              w='Nút ở thanh dưới, khi khay đủ tiền thối.')]


