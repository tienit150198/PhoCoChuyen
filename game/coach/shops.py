def fl_swatch(cmd: str, key: str, ids) -> list[str]:
    """The paper / ribbon the game's own next step names (its payload, or the wrap-and-tie sequence), then the row."""
    one = lambda v: (f"#sheet:has(.gd-next :is([data-seq*='\"{key}\":\"{v}\"'], [data-payload*='\"{key}\":\"{v}\"'])) "
                     f".fl-swatches [data-command=\"{cmd}\"][data-payload*='\"{key}\":\"{v}\"']")
    return [*(one(v) for v in ids), f'.fl-swatches:has([data-command="{cmd}"]:not([disabled]))']

