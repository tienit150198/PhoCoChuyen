def _scaled(amount: int, cat: str) -> int:
    # Tiền đền you pay out goes through the compensation factor (game/compensation.py).
    return -_den(-amount) if cat == 'compensation' and amount < 0 else amount


def F(amount: int, cat: str) -> tuple:
    return ('fund', _scaled(amount, cat), cat)


def W(amount: int, cat: str) -> tuple:
    return ('wallet', _scaled(amount, cat), cat)


def R(outcome: str, *pay, good=None, trust: int = 0, **kw) -> dict:
    return dict(outcome=outcome, pay=list(pay), good=good, trust=trust, **kw)


def L(p: float, win: dict, lose: dict, p_camera: float | None = None) -> dict:
    return dict(p=p, p_camera=p_camera, win=win, lose=lose)


def O(oid: str, label: str, outcome: str, *pay, good=None, hint: str = '', trust: int = 0, **kw) -> dict:
    return dict(id=oid, label=label, outcome=outcome, pay=list(pay), good=good, hint=hint, trust=trust, **kw)


def I(iid: str, cat: str, emoji: str, title: str, text, evidence: list, options: list, careers=ALL, min_day: int = 3,
      tone: str = 'mild', weight: int = 1, default: str | None = None, ticket: dict | None = None, chain: bool = False,
      npc: int = 0, **kw) -> dict:
    return dict(id=iid, cat=cat, emoji=emoji, title=title, text=text, evidence=evidence, options=options,
                careers=tuple(careers), min_day=min_day, tone=tone, weight=weight,
                default=default or options[-1]['id'], ticket=ticket, chain=chain, npc=npc, **kw)


def T(violation: str, amount: int) -> dict:
    return dict(violation=violation, amount=amount)


