# SQLite). "key": the primary key, or the unique key rows are matched by. "unique": other UNIQUE
# keys. "identity": the AUTOINCREMENT column (see reset_sequences). "source": "main" (GAME_DB),
# "limits" (<db>-limits.sqlite3) or None (PostgreSQL only). "sqlite_table": its SQLite name.
