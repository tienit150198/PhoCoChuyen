"""PostgreSQL schema of the game: every table of the main SQLite database plus the
shared rate-limit table `hits` (formerly `<db>-limits.sqlite3`), in one database.

Faithful to the SQLite columns, so rows round-trip byte for byte:
* SQLite TEXT -> text COLLATE "C" (byte order, like SQLite's BINARY collation:
  ORDER BY, comparisons and UNIQUE behave exactly as in SQLite). Timestamps stay
  text 'YYYY-MM-DD HH:MM:SS' (UTC), the format of SQLite's CURRENT_TIMESTAMP.
* SQLite REAL -> double precision, INTEGER -> bigint.
* `sessions.state` stays text (not jsonb): the exact JSON bytes are kept. Its TOAST
  compression is lz4 when the server supports it (PG16 on Ubuntu does), else pglz.
* INTEGER PRIMARY KEY AUTOINCREMENT -> bigint GENERATED BY DEFAULT AS IDENTITY: copied
  ids are kept as they are; after a copy, call reset_sequences(conn, floors) so new
  ids continue after the copied ones (and after SQLite's sqlite_sequence, when given).

Machine-readable description: TABLES (one dict per table, see the keys below).
DDL is split in stages so a bulk copy can run between them:
  TABLES_DDL      tables, primary keys and UNIQUE constraints
  INDEX_DDL       secondary indexes (build after a bulk copy: faster)
  TRIGGER_DDL     the admin-statistics triggers (create them AFTER the initial copy:
                  on a bulk insert into `sessions` they would stamp every save as born today,
                  and one into `receipts` would count every copied command as played now)
  TUNING_DDL      lz4 TOAST compression and autovacuum settings of the hot tables
ensure(conn) runs every stage idempotently (the game server calls it at start-up) and
records SCHEMA_VERSION in `mnl_meta`, so later start-ups skip the DDL (and its locks).

Delta-sync hints (TABLES[i]["sync"]):
  {"mode": "revision", ...}  rows change in place; a row changed iff its `revision`
                             differs (sessions: every save write bumps revision;
                             updated_at is NOT touched by save migrations on read).
  {"mode": "insert_only", "column": c}  rows are only inserted (and deleted);
                             `c` grows with time. Deleted rows must be found by key.
  {"mode": "updated", "column": c}  every UPDATE sets `c` (plus inserts/deletes).
  {"mode": "full"}           small or updated without a marker: copy it whole.
"""
from __future__ import annotations

SCHEMA_VERSION = 3   # 2: leaderboard, marriage/friends/couple tables, stat_fb_created, stat_accounts_created; 3: stat_play

# The text forms SQLite produces, computed by PostgreSQL (UTC, independent of TimeZone).
NOW_TEXT = "to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')"       # CURRENT_TIMESTAMP
UNIXEPOCH = "floor(extract(epoch FROM statement_timestamp()))"                                # unixepoch()
VN_DAY = "to_char((statement_timestamp() AT TIME ZONE 'UTC') + interval '7 hours', 'YYYY-MM-DD')"  # date('now','+7 hours')

# Play time (stat_play, the same rule as game/admin_stats.py SCHEMA): a command within PLAY_GAP seconds
# of the save's previous one that day continues the session (the gap counts as played); a longer gap
# starts a new session. Each session also counts PLAY_IDLE_TAIL seconds after its last command.
PLAY_GAP = 600
PLAY_IDLE_TAIL = 60

T = 'text COLLATE "C"'          # every SQLite TEXT column
