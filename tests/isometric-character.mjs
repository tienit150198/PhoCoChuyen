import assert from 'node:assert/strict';
import {atlasCell,characterKey,recolourPixel} from '../public/js/isometric/character-art.js';
assert.deepEqual(atlasCell('sw'),{x:0,y:0});
assert.deepEqual(atlasCell('se'),{x:1,y:0});
assert.deepEqual(atlasCell('nw'),{x:2,y:0});
assert.deepEqual(atlasCell('ne'),{x:3,y:0});
assert.deepEqual(atlasCell('sw',1),{x:0,y:1});
assert.deepEqual(atlasCell('ne',2),{x:3,y:2});
assert.deepEqual(atlasCell('ne',99),{x:3,y:2});
assert.deepEqual(atlasCell('invalid'),atlasCell('se'));
const a={gender:'male',direction:'sw',look:{top:'ao_hoa',tint:{ao_hoa:'mint'}}};
assert.notEqual(characterKey(a),characterKey({...a,direction:'ne'}));
assert.notEqual(characterKey(a),characterKey({...a,walkFrame:1}),'a walking frame never reuses the idle texture');
assert.notEqual(characterKey({...a,walkFrame:1}),characterKey({...a,walkFrame:2}),'alternating steps have distinct textures');
assert.notEqual(characterKey(a),characterKey({...a,look:{...a.look,tint:{ao_hoa:'hong'}}}));
assert.notEqual(characterKey(a),characterKey({...a,uniformColor:'#a43f35'}));
const palette={hair:'#edaf78',skin:'#c48d64',top:'#3a4e7c',bottom:'#e39ab0',shoes:'#3d3533'};
assert.deepEqual(recolourPixel([10,20,30,0],.2,palette),[10,20,30,0]);
assert.deepEqual(recolourPixel([38,29,25,255],.2,palette),[38,29,25,255],'dark outlines are preserved');
assert.deepEqual(recolourPixel([252,249,245,255],.32,palette),[252,249,245,255],'eye highlights remain white');
const shirt=recolourPixel([221,211,190,202],.65,palette);
assert.equal(shirt[3],202,'alpha is unchanged');
assert.ok(shirt[2]>shirt[0],'navy shirt uses chosen hue');
const trousers=recolourPixel([72,92,124,255],.83,palette);
assert.ok(trousers[0]>trousers[1],'pink trousers use chosen hue');
const apron=recolourPixel([68,97,100,255],.76,palette);
assert.ok(apron[2]>apron[0],'muted teal apron uses chosen shirt hue, not the trouser mask');
console.log('Illustrated character direction, wardrobe palette and alpha checks passed');
