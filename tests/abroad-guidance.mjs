import assert from 'node:assert/strict';
import {abroadView} from '../public/js/v4/abroad.js';
const A={study:null,deg:[],work:null,rest_until:0,jobs:[{career:'pharmacy',pay:100,title:'Nhân viên',why:''}],shop:{career:'clothing',why:''}};
const K={dests:[{id:'kr',flag:'🇰🇷',name:'Hàn Quốc',city:'Seoul'}],work:{kr:{days:3,pct:20,fee:100}},shop:{kr:{name:'Tiệm áo',days:3,pct:10}},programs:{kr:{school:'Trường học',course:'Khóa học',lessons:3,fee:500}},deg_pct:[0,10,15,20],good_cut:20,grades:{},scholar:20};
const env={ui:{abTab:'work'},api:{state:{current:'pharmacy',journey:{story:true,life_day:130,abroad:A},careers:{pharmacy:{open:true},accounting:{open:true},salon:{open:false}}},content:{journey:{abroad:K},catalogue:[{id:'pharmacy',place:'Nhà thuốc'},{id:'accounting',place:'Góc Sổ Xinh'},{id:'clothing',place:'Tiệm áo'}]}}};
let html=abroadView(env);
assert.match(html,/Còn 2 ca đang mở/);
assert.match(html,/data-action="choose" data-career="pharmacy"/);
assert.match(html,/data-action="choose" data-career="accounting"/);
assert.equal((html.match(/data-op="jr_abroad_work"[^>]*disabled/g)||[]).length,2);
env.api.state.careers.pharmacy.open=false;
html=abroadView(env);
assert.match(html,/Còn 1 ca đang mở/);
assert.doesNotMatch(html,/data-action="choose" data-career="pharmacy"/);
env.api.state.careers.accounting.open=false;
html=abroadView(env);
assert.doesNotMatch(html,/Còn \d+ ca đang mở/);
assert.doesNotMatch(html,/data-op="jr_abroad_work"[^>]*disabled/);
env.ui={abTab:'study',abLast:{ok:true,text:'Đã học xong buổi 1'}};
A.study={p:'kr',n:1,of:3,lesson:null};
html=abroadView(env);
assert.match(html,/ngày sống mới/);
assert.match(html,/không cần chờ sang ngày ngoài đời/i);
assert.match(html,/buổi 2/);
assert.match(html,/data-action="choose" data-career="pharmacy"/);
A.study.lesson={scene:'Cảnh',q:'Câu hỏi',options:['A','B','C']};
assert.doesNotMatch(abroadView(env),/không cần chờ sang ngày ngoài đời/i);
// 📲 Đóng ca từ xa (v4/remote-close.js, game/remote_close.py): without the device a hint says what to buy and where, and
// "Về …" stays; with it each open shift gets its own remote button (the same end_day, payload {remote:true}).
A.study=null;env.ui={abTab:'work'};
env.api.state.careers.pharmacy.open=true;env.api.state.careers.accounting.open=true;
const shops=[{career:'pharmacy',day:4,done:2,left:1,event:true,here:true},{career:'accounting',day:7,done:0,left:0,event:false,here:false}];
env.api.content.journey.gadgets={shop:'Mây Mobile',where:'Phố dịch vụ',items:[{id:'quan_ly_xa',emoji:'📲',name:'Máy quản lý từ xa',price:5500}]};
env.api.state.journey.remote={own:false,item:'quan_ly_xa',shops};
html=abroadView(env);
assert.match(html,/🔒 Muốn khép ca từ xa/);
assert.match(html,/5\.500 xu/);
assert.match(html,/data-action="gadgets" data-tab="tool"/);
assert.match(html,/data-action="choose" data-career="accounting"/);
assert.doesNotMatch(html,/data-action="rcClose"/);
env.api.state.journey.remote={own:true,item:'quan_ly_xa',shops};
html=abroadView(env);
assert.match(html,/data-action="rcClose" data-career="pharmacy"/);
assert.match(html,/data-action="rcClose" data-career="accounting"/);
assert.match(html,/còn 1 việc để mai · chuyện đang dở mang sang mai/);
assert.doesNotMatch(html,/🔒 Muốn khép ca từ xa/);
const rc=await import('../public/js/v4/remote-close.js');
assert.deepEqual(rc.away(env.api).map(x=>x.career),['accounting']);
assert.match(rc.remoteView(env),/2 ca đang mở/);
env.api.state.journey.remote={own:true,item:'quan_ly_xa',shops:[]};env.ui.rcLast={career:'accounting',text:'✓ Đã khép ca ở Góc Sổ Xinh, +40 xu trong ca.'};
assert.match(rc.remoteView(env),/Không còn ca nào đang mở/);
assert.match(rc.remoteView(env),/✓ Đã khép ca ở Góc Sổ Xinh/);
console.log('Abroad: all open shifts, partial closure and next-life-day study guidance, remote close passed.');
