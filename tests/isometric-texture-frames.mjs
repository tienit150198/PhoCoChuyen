import assert from 'node:assert/strict';
import {build} from 'esbuild';
const compiled=await build({entryPoints:['client/isometric/texture-frames.ts'],bundle:true,write:false,platform:'node',format:'esm',logLevel:'silent'});
const {TextureFrames}=await import('data:text/javascript;base64,'+Buffer.from(compiled.outputFiles[0].text).toString('base64'));
const live=new Set(),made=[],removed=[],cache=new TextureFrames(key=>{assert.ok(live.delete(key));removed.push(key);});
const create=key=>{assert.ok(!live.has(key));live.add(key);made.push(key);};
const first=cache.get('player','outfit-a','se:0',create);
for(let tick=0;tick<200;tick++)cache.get('player','outfit-a','se:'+tick%3,create);
assert.equal(made.length,3,'walking reuses its three poses rather than uploading each step');
assert.equal(removed.length,0,'poses stay alive between animation ticks');
assert.equal(cache.get('player','outfit-a','se:0',create),first);
for(const direction of ['sw','se','nw','ne'])for(let frame=0;frame<3;frame++)cache.get('player','outfit-a',direction+':'+frame,create);
assert.equal(cache.size,12,'one appearance has at most twelve directional poses');
cache.get('peer','outfit-a','se:0',create);
cache.get('player','outfit-b','se:0',create);
assert.equal(cache.size,2,'wardrobe changes release old poses, without touching another actor');
assert.equal(removed.length,12);
cache.release('peer');assert.equal(cache.size,1);
cache.clear();assert.equal(cache.size,0);assert.equal(live.size,0);
cache.release('peer');cache.clear();
console.log('Character textures: animation reuse, wardrobe invalidation and bounded lifetime passed');
