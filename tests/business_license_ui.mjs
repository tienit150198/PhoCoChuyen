import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
assert.ok(existsSync(new URL('../public/js/v4/business-license-ui.js',import.meta.url)), 'Business license UI is available');
const {licensePanel,licenseRequirement,licenseNotice,preferStall}=await import('../public/js/v4/business-license-ui.js');
const license={enabled:true,status:'grace',level:0,required_level:3,next_cert:'business_basics',deadline:1800000000,
  courses:[{id:'business_basics',name:'Kinh doanh cơ bản',fee:550,earned:false},{id:'business_advanced',name:'Quản lý cửa tiệm',fee:2200,earned:false}],
  allowed_ids:['q1'],blocked_ids:[],preferred_ids:[]};
assert.equal(licensePanel(null),'');
assert.equal(licenseNotice({...license,status:'compliant'}),'');
assert.equal(licenseNotice({...license,enabled:false}),'');
let html=licensePanel(license);
assert.match(html,/Công an kiểm tra/);
assert.match(html,/72 giờ/);
assert.match(html,/550/);
assert.doesNotMatch(licensePanel({...license,required_level:1}),/Quản lý cửa tiệm/);
const retake={...license,courses:[{...license.courses[0],enrol_fee:275}]};
assert.match(licensePanel(retake),/275 xu/);
assert.match(licenseRequirement({allowed:false,next_cert:'business_basics'},retake),/275 xu/);
assert.match(html,/data-cert="business_basics"/);
assert.doesNotMatch(html,/Tự học|data-mode="self"/);
html=licensePanel({...license,status:'restricted',blocked_ids:['q2','q3']});
assert.match(html,/2 quầy/);
assert.match(html,/không phát sinh/);
assert.match(html,/đơn đã nhận/);
assert.match(licenseNotice(license),/data-action="quay"/);
assert.match(licenseNotice(license),/Bổ sung chứng chỉ/);
assert.match(licenseRequirement({allowed:false,next_cert:'business_basics',reason:'Cần học <script>'},license),/Cần học &lt;script&gt;/);
assert.match(licenseRequirement({allowed:true,required_level:0},license),/Không cần chứng chỉ/);
assert.deepEqual(preferStall(['q1','q2','q3'],['q2'],'q3'),['q3','q2','q1']);
assert.deepEqual(preferStall(['q1','q2'],['gone','q2','q2'],'q1'),['q1','q2']);
assert.deepEqual(preferStall(['q1','q2'],[],'forged'),[]);
const {openAll}=await import('../public/js/v4/quay-manage.js');
const {businessControls}=await import('../public/js/v4/business-economy-ui.js');
const blockedControls=businessControls({id:'q2',license_blocked:true,business:{paused:true}},(label,op,data,style,why)=>`<button ${why?'disabled':''}>${label}</button>`);
assert.match(blockedControls,/disabled/);
assert.match(blockedControls,/bổ sung chứng chỉ/);
assert.doesNotMatch(businessControls({id:'q2',license_blocked:true,business:{paused:false}},()=>''),/Quầy đang mở nhận khách/);
assert.deepEqual(openAll([{id:'q1',business:{paused:true},license_blocked:true},{id:'q2',business:{paused:true}}]).steps,[{stall:'q2',on:false}]);
console.log('Business license notices, requirements, priority selection and bulk reopening passed.');
