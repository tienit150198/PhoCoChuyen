import assert from 'node:assert/strict';
import {createSitePresence,sitePresence} from '../public/js/v4/site-presence.js';
const listeners=new Map(),frames=[],socket={state:'open',flags:{town:true},on(t,fn){const a=listeners.get(t)||new Set();a.add(fn);listeners.set(t,a);return()=>a.delete(fn);},send(f){frames.push(f);return true;}};
const emit=(t,f)=>{for(const fn of listeners.get(t)||[])fn(f);};
let joined,closed,people=[];
const p=createSitePresence({owner:'0123456789abcdef',career:'grocery',site:'base'}, {transport:socket,onJoin:f=>joined=f,onPeers:p=>people=p,onClose:r=>closed=r});
const ready=p.start();assert.equal(sitePresence.active,true);assert.equal(frames.at(-1).t,'site_in');
emit('town_room',{map:'iso-town-v1',room:'street'});assert.equal(joined,undefined);
emit('town_room',{map:'scale-site-v1',room:'scale-site-v1:x',cid:frames.at(-1).cid,me:'a',people:[{pid:'b',x:10,y:16,name:'B'}]});await ready;assert.equal(people.length,1);
p.move({x:230,y:325,direction:'ne'});assert.equal(frames.at(-1).x,11.5);
emit('town',{room:'street',ev:[{k:'in',pid:'c'}]});assert.equal(people.length,1);
emit('down',{});assert.equal(people.length,0);emit('welcome',{});assert.equal(frames.at(-1).t,'site_in');
emit('town_room',{map:'scale-site-v1',room:'scale-site-v1:x',cid:frames.at(-1).cid,me:'a',people:[]});
emit('town_left',{why:'private',room:'scale-site-v1:x'});assert.equal(closed,'private');assert.equal(sitePresence.active,false);
assert.equal([...listeners.values()].reduce((n,x)=>n+x.size,0),0);
console.log('site presence isolation, reconnect and cleanup passed');
